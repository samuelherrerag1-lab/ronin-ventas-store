from typing import List
from backend.models.catalog_models import PinterestPinItem


def _pin(
    pin_id: str,
    lane: str,
    head: str,
    badge: str,
    title: str,
    desc: str,
    board: str,
    route: str,
    sku: str,
    engine: str,
    theme: str,
    img: str,
    saves: int,
    clicks: int,
    is_bench: bool = False,
    bench_src: str = "",
) -> PinterestPinItem:
    return PinterestPinItem(
        pin_id=pin_id,
        strategy_lane=lane,  # type: ignore
        overlay_headline=head,
        overlay_badge=badge,
        seo_title=title,
        seo_description=desc,
        board_name=board,
        bridge_route=route,
        target_sku_id=sku,
        visual_engine=engine,  # type: ignore
        visual_theme=theme,
        image_url=img,
        simulated_saves=saves,
        simulated_outbound_clicks=clicks,
        is_competitor_benchmark=is_bench,
        competitor_source=bench_src,
    )


